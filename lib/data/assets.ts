export function coverageFromDate(expiry?: string): import("./types").CoverageStatus {
  if (!expiry) return "None";
  const days = Math.round(
    (new Date(`${expiry}T00:00:00`).getTime() - new Date("2026-09-12T00:00:00").getTime()) /
      86_400_000
  );
  if (days < 0) return "Expired";
  if (days <= 45) return "Expiring";
  return "Active";
}
